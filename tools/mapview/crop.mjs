/**
 * 中央の島を **81 マス幅**に切り詰める。
 *
 * ## なぜ要るか
 *
 * 生成器は 82 マス角で島を作るが、**城は内部の列 41 を中心に対称**に建っている。
 * 82（偶数）だと箱の中心は 40.5 になり、**城の中心と半マスずれる。**
 *
 * その結果:
 *
 * - 西と北に、対称の相手がいない列が 1 列だけ余る
 * - 回転コピーの軸をどこに置くかが曖昧になる（1000 か 999.5 か）
 * - 実際に「サイズが合わない」「門がずれる」の原因になった
 *
 * **列 0 と行 0 を落として 81 にすると、中心が列 40（世界 1000）に一致し、
 * 90 度回転が (x,z) → (80-z, x) で過不足なく閉じる。** 余りの列は無くなる。
 */

import { Voxels } from "./voxel.mjs";

/** 幅 82 の器から、列 0 と行 0 を落とした 81 幅の器を作る */
export function cropTo81(v) {
  if (v.sx !== 82 || v.sz !== 82) {
    throw new Error(`82x82 を想定しているが ${v.sx}x${v.sz} だった`);
  }
  const out = new Voxels(81, v.sy, 81);
  for (let y = 0; y < v.sy; y++)
    for (let z = 0; z < 81; z++)
      for (let x = 0; x < 81; x++)
        out.set(x, y, z, v.get(x + 1, y, z + 1));
  return out;
}

/** 81 幅の器における中心（世界 1000 に対応する内部座標） */
export const CENTER_IN = 40;
